#!/usr/bin/env python3
"""
regenerate_data_modules.py
==========================

Regenerates the TypeScript data modules from the updated CSVs in data_raw/:
  - data_raw/all_pesticides.csv → src/data/all_pesticides.ts
  - data_raw/pesticide_policy_enrichment.csv → src/data/policyEnrichmentData.ts

This is a self-contained version of the two original scripts that:
  - Reads from the repo's data_raw/ directory (not an external path)
  - Preserves the existing TypeScript interface definitions
  - Generates clean TS modules that import cleanly into the app
"""

from __future__ import annotations
import csv
import sys
from pathlib import Path
import pandas as pd

REPO = Path(__file__).resolve().parent.parent
DAE_CSV = REPO / "data_raw" / "all_pesticides.csv"
POLICY_CSV = REPO / "data_raw" / "pesticide_policy_enrichment.csv"
ALL_PESTICIDES_TS = REPO / "src" / "data" / "all_pesticides.ts"
POLICY_TS = REPO / "src" / "data" / "policyEnrichmentData.ts"


def log(msg: str) -> None:
    print(f"[regen] {msg}", flush=True)


def to_ts_string_literal(s) -> str:
    """Convert a Python str into a TS double-quoted string literal."""
    if s is None:
        return "null"
    if isinstance(s, float) and s != s:  # NaN check
        return "null"
    s = str(s)
    if s.strip().lower() in ("nan", "na", "none", "null", ""):
        return "null"
    s = s.replace("\\", "\\\\")
    s = s.replace('"', '\\"')
    s = s.replace("\n", "\\n")
    s = s.replace("\r", "")
    return f'"{s}"'


def to_ts_number(value: str) -> str:
    value = (value or "").strip()
    if not value:
        return "0"
    try:
        if value.isdigit():
            return str(int(value))
        return str(float(value))
    except ValueError:
        return "0"


def normalize_reg_no(s) -> str:
    if s is None or pd.isna(s):
        return ""
    return str(s).strip().upper()


# ----------------------------------------------------------------------------
# Regenerate all_pesticides.ts
# ----------------------------------------------------------------------------
HEADER_COMMENT_ALL = '''/**
 * Registered pesticides in Bangladesh — full database.
 * Source: Department of Agricultural Extension (DAE), Bangladesh —
 * List of Registered Pesticides merged with the live pesticide-search API
 * (ppw.krishi.gov.bd) and the 86th / 87th PTAC gazette editions.
 *
 * Auto-generated from data_raw/all_pesticides.csv. Do not edit by hand.
 * Last regenerated by: scripts/regenerate_data_modules.py
 * Multi-line ``recommendations`` fields preserve the original CSV newline
 * separators as the escape sequence ``\\n`` inside the string literal.
 */

'''

TYPE_BLOCK_ALL = '''export type PesticideType =
  | "Insecticide"
  | "Fungicide"
  | "Herbicide"
  | "Public Health"
  | "Miticide"
  | "Store Grain Insecticide"
  | "Bio Pesticide"
  | "Rodenticide";

export interface PesticideProduct {
  /** Pesticide category (e.g. "Insecticide", "Fungicide"). */
  pesticideType: PesticideType;
  /** Common-name index (1-based) used to group brand variants within a type. */
  slNoCommonName: number;
  /** Active ingredient / technical common name. */
  commonName: string;
  /** Sequence number of the brand variant under its common name. */
  slNoProduct: number;
  /** Trade / brand name of the formulated product. */
  brandName: string;
  /** DAE registration number, e.g. "AP-890" or "PHP-769". */
  registrationNo: string;
  /** Company that holds the registration. */
  registrationHolder: string;
  /** Crops the product is recommended for. */
  recommendedCrops: string[];
  /** Pest(s) the product is recommended against. */
  recommendedPests: string[];
  /** Human-readable dosage rate summary. */
  dosageRate: string;
  /** Crop | Pest | Dosage breakdown, one per line. */
  recommendations: string;
  /** Number of separate crop-pest-dosage recommendations. */
  noOfRecommendations: number;
  /** IRAC / FRAC Mode-of-Action code, if classified. */
  moaCode: string | null;
}

'''


def regen_all_pesticides() -> int:
    """Regenerate src/data/all_pesticides.ts from data_raw/all_pesticides.csv."""
    log(f"Reading {DAE_CSV}...")
    if not DAE_CSV.exists():
        log(f"ERROR: {DAE_CSV} not found", file=sys.stderr)
        return 1
    with DAE_CSV.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = list(reader)
    log(f"  {len(rows):,} rows × {len(header)} cols")

    out_lines = [HEADER_COMMENT_ALL, TYPE_BLOCK_ALL, "export const pesticides: ReadonlyArray<PesticideProduct> = ["]
    multiline_count = 0
    skipped = 0
    for row in rows:
        if len(row) < 13:
            skipped += 1
            continue
        (
            pest_type,
            sl_no_common_name,
            common_name,
            sl_no_product,
            brand_name,
            reg_no,
            reg_holder,
            rec_crops,
            rec_pests,
            dosage_rate,
            recommendations,
            no_of_recs,
            moa_code,
        ) = row[:13]
        crops = [c.strip() for c in rec_crops.split(",") if c.strip()]
        pests = [p.strip() for p in rec_pests.split(",") if p.strip()]
        recommendations = recommendations.strip("\n").strip()
        if "\n" in recommendations:
            multiline_count += 1
        moa_code_lit = "null" if not moa_code.strip() else to_ts_string_literal(moa_code.strip())
        out_lines.append("  {")
        out_lines.append(f"    pesticideType: {to_ts_string_literal(pest_type.strip())} as PesticideType,")
        out_lines.append(f"    slNoCommonName: {to_ts_number(sl_no_common_name)},")
        out_lines.append(f"    commonName: {to_ts_string_literal(common_name.strip())},")
        out_lines.append(f"    slNoProduct: {to_ts_number(sl_no_product)},")
        out_lines.append(f"    brandName: {to_ts_string_literal(brand_name.strip())},")
        out_lines.append(f"    registrationNo: {to_ts_string_literal(reg_no.strip())},")
        out_lines.append(f"    registrationHolder: {to_ts_string_literal(reg_holder.strip())},")
        out_lines.append(f"    recommendedCrops: [{', '.join(to_ts_string_literal(c) for c in crops)}],")
        out_lines.append(f"    recommendedPests: [{', '.join(to_ts_string_literal(p) for p in pests)}],")
        out_lines.append(f"    dosageRate: {to_ts_string_literal(dosage_rate.strip())},")
        out_lines.append(f"    recommendations: {to_ts_string_literal(recommendations)},")
        out_lines.append(f"    noOfRecommendations: {to_ts_number(no_of_recs)},")
        out_lines.append(f"    moaCode: {moa_code_lit},")
        out_lines.append("  },")
    out_lines.append("];")
    out_lines.append("")
    ALL_PESTICIDES_TS.write_text("\n".join(out_lines), encoding="utf-8")
    log(f"  Wrote {ALL_PESTICIDES_TS} ({ALL_PESTICIDES_TS.stat().st_size:,} bytes)")
    log(f"  {multiline_count} multiline recommendations, {skipped} skipped rows")
    return 0


