# Regenerate policyEnrichmentData.ts
# ----------------------------------------------------------------------------
HEADER_COMMENT_POLICY = '''/**
 * policyEnrichmentData.ts — Auto-generated sidecar policy/HHP/MoA enrichment
 * ====================================================================
 * Source: data_raw/pesticide_policy_enrichment.csv
 * Merged from the AgriChem/MoA PTAC master database (5,485 rows) and the
 * updated MoA mapping audit CSV (5,437 rows) for the 86th/87th PTAC editions.
 *
 * Each record is keyed by normalized Registration No (uppercase, trimmed)
 * and carries the 14 policy / HHP / MoA / formulation safety attributes
 * that were missing from the original 13-column DAE CSV.
 *
 * DO NOT EDIT BY HAND. Re-run scripts/regenerate_data_modules.py to
 * regenerate from data_raw/pesticide_policy_enrichment.csv.
 */

'''

INTERFACE_BLOCK_POLICY = '''export interface PolicyEnrichment {
  /** IRAC / FRAC / HRAC scheme tag. */
  scheme: string | null;
  /** MoA group number within the scheme (e.g. "1B", "11"). */
  groupNo: string | null;
  /** Human-readable MoA description. */
  moaDescription: string | null;
  /** Target site of action. */
  targetSite: string | null;
  /** WHO/FAO Highly Hazardous Pesticide (HHP) status. */
  hhpStatus: string | null;
  /** Active ingredient(s) that triggered HHP classification, if any. */
  hazardousActivesMatched: string | null;
  /** Whether the product meets HHP criteria ("YES — HHP" / "No — ..."). */
  hhpCriteriaMet: string | null;
  /** EU / global regulatory status (banned, restricted, approved, etc.). */
  euGlobalRegulatoryStatus: string | null;
  /** Bangladesh-specific policy action (phase-out, restrict, monitor, etc.). */
  bangladeshPolicyAction: string | null;
  /** Policy risk tier: GREEN (safe) | AMBER (caution) | RED (ban/restrict). */
  policyRiskTier: string | null;
  /** Short formulation code (EC, WP, SC, etc.). */
  formulationCode: string | null;
  /** Physicality of the formulation (liquid, solid, etc.). */
  formulationTypePhysicality: string | null;
  /** Free-text physical form description. */
  physicalForm: string | null;
  /** Co-formulant / inert concern flags. */
  coFormulantInertConcern: string | null;
}

'''


def regen_policy_enrichment() -> int:
    """Regenerate src/data/policyEnrichmentData.ts from data_raw/pesticide_policy_enrichment.csv."""
    log(f"Reading {POLICY_CSV}...")
    if not POLICY_CSV.exists():
        log(f"ERROR: {POLICY_CSV} not found", file=sys.stderr)
        return 1
    df = pd.read_csv(POLICY_CSV, dtype=str).fillna("")
    log(f"  {len(df):,} rows × {len(df.columns)} cols")

    # Build reg# → row map (first-write-wins)
    by_reg_no = {}
    for _, row in df.iterrows():
        key = normalize_reg_no(row.get("Registration No", ""))
        if not key or key in by_reg_no:
            continue
        by_reg_no[key] = row

    ts_lines = [
        HEADER_COMMENT_POLICY,
        INTERFACE_BLOCK_POLICY,
        "export const POLICY_ENRICHMENT_BY_REG_NO: Record<string, PolicyEnrichment> = {",
    ]
    for key, row in by_reg_no.items():
        ts_lines.append(f"  {to_ts_string_literal(key)}: {{")
        ts_lines.append(f"    scheme: {to_ts_string_literal(row.get('Scheme'))},")
        ts_lines.append(f"    groupNo: {to_ts_string_literal(row.get('Group No.'))},")
        ts_lines.append(f"    moaDescription: {to_ts_string_literal(row.get('MoA Description'))},")
        ts_lines.append(f"    targetSite: {to_ts_string_literal(row.get('Target Site'))},")
        ts_lines.append(f"    hhpStatus: {to_ts_string_literal(row.get('HHP Status (WHO/FAO)'))},")
        ts_lines.append(f"    hazardousActivesMatched: {to_ts_string_literal(row.get('Hazardous Active(s) Matched'))},")
        ts_lines.append(f"    hhpCriteriaMet: {to_ts_string_literal(row.get('HHP Criteria Met'))},")
        ts_lines.append(f"    euGlobalRegulatoryStatus: {to_ts_string_literal(row.get('EU / Global Regulatory Status'))},")
        ts_lines.append(f"    bangladeshPolicyAction: {to_ts_string_literal(row.get('Bangladesh Policy Action'))},")
        ts_lines.append(f"    policyRiskTier: {to_ts_string_literal(row.get('Policy Risk Tier'))},")
        ts_lines.append(f"    formulationCode: {to_ts_string_literal(row.get('Formulation Code'))},")
        ts_lines.append(f"    formulationTypePhysicality: {to_ts_string_literal(row.get('Formulation Type (Physicality)'))},")
        ts_lines.append(f"    physicalForm: {to_ts_string_literal(row.get('Physical Form'))},")
        ts_lines.append(f"    coFormulantInertConcern: {to_ts_string_literal(row.get('Co-formulant / Inert Concern'))},")
        ts_lines.append("  },")
    ts_lines.append("};")
    ts_lines.append("")
    ts_lines.append("/** Convenience lookup helper. */")
    ts_lines.append("export function getPolicyEnrichment(registrationNo: string | null | undefined): PolicyEnrichment | null {")
    ts_lines.append("  if (!registrationNo) return null;")
    ts_lines.append("  const key = registrationNo.trim().toUpperCase();")
    ts_lines.append("  return POLICY_ENRICHMENT_BY_REG_NO[key] ?? null;")
    ts_lines.append("}")
    ts_lines.append("")

    POLICY_TS.write_text("\n".join(ts_lines), encoding="utf-8")
    log(f"  Wrote {POLICY_TS} ({POLICY_TS.stat().st_size:,} bytes, {len(by_reg_no):,} unique reg#s)")
    return 0


def main() -> int:
    rc1 = regen_all_pesticides()
    rc2 = regen_policy_enrichment()
    return rc1 or rc2


if __name__ == "__main__":
    sys.exit(main())
